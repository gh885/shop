package com.shop.platform.common;

/**
 * 「人手写的一段说明」的长度口径：留言 / 取消原因 / 售后理由 / 拒绝理由 / 结单备注 / 轨迹描述 / 地址备注共用一份。
 *
 * <p>这一档此前散在七个 DTO 里各写一遍 {@code @Size(max = 200)}，其中四处还各自把数字抄进了 message 文案
 * （「补充说明最长 200 字」「拒绝理由最长 200 字」「取消原因最多 200 字」「留言最多 200 字」）。
 * 七份今天逐字节相同，而漂移是无声的：改一处放宽，另外六处的入口还按老上限放行，
 * 卖家与买家按入口不同拿到不同的字数上限，测试各测各的都不红。
 *
 * <p><b>为什么 200 这一档值得收成一份而 {@code refreshToken} 的 200 不收</b>：收成一份的依据是<b>概念</b>
 * 而不是数字——这七格都是「给人看的自由文本，落点列宽 {@code VARCHAR(200)}」，改任何一格都同时改变
 * 用户在全部这些框里能写的字数；而 {@code RefreshRequest.refreshToken} 的 200 是<b>不透明令牌的容量</b>，
 * 与字数预算无关（它是 base64 串，不是文本框）。同一个数字服务两个概念时，按数字合并就是把两个概念绑死，
 * 日后换令牌签名算法要先拆掉一个字段文案。
 *
 * <p>注解元素值必须是编译期常量表达式，所以这里是常量；文案里的数字由本常量拼出，改上限即改文案，
 * 不会留下「上限 300、提示 200」这种自相矛盾的界面。
 */
public final class NoteFieldRules {

    /** 一段人写的说明上限（字）：与它落点那一列的宽度同值（各 {@code VARCHAR(200)}），入口不越过库上那一格 */
    public static final int FREE_TEXT_MAX = 200;

    private NoteFieldRules() {}
}
